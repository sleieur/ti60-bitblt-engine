int font_index(char c)
{
    for (int i = 0; FONT_CHARS[i]; i++)
        if (FONT_CHARS[i] == c) return i;
    return 0;                                   /* unknown -> space */
}

int hwt_len(const char *s)
{
    int n = 0;
    while (*s++) n++;
    return n * GLYPH_CELL_W;
}
